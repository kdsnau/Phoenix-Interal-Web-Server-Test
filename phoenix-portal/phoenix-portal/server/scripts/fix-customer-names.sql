SELECT c.customer_id, left(c.name,34) AS old_name, q.name AS clean_name
FROM clients c JOIN qb q ON c.customer_id = q.num
WHERE c.customer_id ~ '^[0-9]{3,4}$' AND c.name IS DISTINCT FROM q.name
ORDER BY c.customer_id LIMIT 40;

\echo ''
\echo '=== count to be renamed ==='
SELECT count(*) AS renaming
FROM clients c JOIN qb q ON c.customer_id = q.num
WHERE c.customer_id ~ '^[0-9]{3,4}$' AND c.name IS DISTINCT FROM q.name;

-- ===================== APPLY (name only, no deletes) =====================
UPDATE clients c SET name = q.name
FROM qb q
WHERE c.customer_id = q.num AND c.customer_id ~ '^[0-9]{3,4}$' AND c.name IS DISTINCT FROM q.name;

\echo ''
\echo '=== AFTER (total clients unchanged) ==='
SELECT count(*) AS clients FROM clients;

ROLLBACK;  -- <<< change to COMMIT and re-run to apply
